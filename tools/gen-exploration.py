"""
Writes Data/Exploration.lua for the Retail addon and for the WoW Forever addon: every explorable region of every zone map,
read from the game's own tables (wago.tools exports of WorldMapOverlay, UiMapXMapArt, UiMapArt and UiMapArtStyleLayer).

    python tools/gen-exploration.py                       # builds below
    python tools/gen-exploration.py --retail 12.1.5.70961 --forever 1.60.1.71037

Run it again after a patch (give the new build numbers). The downloaded tables are kept in tools/_wago_cache/.

What each entry holds, per zone map (UiMapID):
    { offsetX, offsetY, textureWidth, textureHeight, centerX, centerY, areaID }
The first four are the fog piece exactly as C_MapExplorationInfo.GetExploredMapTextures reports it when the region has been
discovered (that is how the addon tells discovered from not). centerX/centerY are the middle of the region on the map, from
0 to 1 (the middle of its hit rectangle when the game defines one, otherwise of its texture), already divided by the map art's
size. Overlays that depend on a player condition, or that have no fog piece, are left out: they could never show as discovered.
"""
import argparse
import csv
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CACHE = Path(__file__).resolve().parent / "_wago_cache"
TABLES = ["WorldMapOverlay", "UiMapXMapArt", "UiMapArt", "UiMapArtStyleLayer"]

TARGETS = {
    "retail": ROOT / "SuperNovaUI" / "Data" / "Exploration.lua",
    "forever": ROOT.parent / "SuperNovaUI-Forever" / "SuperNovaUI_Forever" / "Data" / "Exploration.lua",
}
DEFAULT_BUILDS = {"retail": "12.1.5.70961", "forever": "1.60.1.71037"}


def fetch(table, build):
    CACHE.mkdir(exist_ok=True)
    path = CACHE / f"{build}_{table}.csv"
    if not path.exists():
        url = f"https://wago.tools/db2/{table}/csv?build={build}"
        request = urllib.request.Request(url, headers={"User-Agent": "gen-exploration"})
        with urllib.request.urlopen(request, timeout=90) as response:
            path.write_bytes(response.read())
    with path.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def build_zones(build):
    overlays = fetch("WorldMapOverlay", build)
    x_art = fetch("UiMapXMapArt", build)
    art_style = {row["ID"]: row["UiMapArtStyleID"] for row in fetch("UiMapArt", build)}
    layers = {row["UiMapArtStyleID"]: row for row in fetch("UiMapArtStyleLayer", build) if row["LayerIndex"] == "0"}

    maps_of_art = {}
    for row in x_art:
        maps_of_art.setdefault(row["UiMapArtID"], set()).add(int(row["UiMapID"]))

    overlays_of_art = {}
    for row in overlays:
        overlays_of_art.setdefault(row["UiMapArtID"], []).append(row)

    zones = {}
    skipped = 0
    for art_id, rows in overlays_of_art.items():
        layer = layers.get(art_style.get(art_id))
        if not layer:
            skipped += len(rows)
            continue

        width, height = int(layer["LayerWidth"]), int(layer["LayerHeight"])

        for ui_map in maps_of_art.get(art_id, ()):
            entries = zones.setdefault(ui_map, {})
            for row in rows:
                if row["PlayerConditionID"] != "0":
                    continue

                offset_x, offset_y = int(row["OffsetX"]), int(row["OffsetY"])
                tex_w, tex_h = int(row["TextureWidth"]), int(row["TextureHeight"])
                if tex_w <= 0 or tex_h <= 0:
                    continue  # no fog piece to draw, so the game never reports it as explored
                left, right = int(row["HitRectLeft"]), int(row["HitRectRight"])
                top, bottom = int(row["HitRectTop"]), int(row["HitRectBottom"])

                if right > left and bottom > top:
                    center_x, center_y = (left + right) / 2, (top + bottom) / 2
                else:
                    center_x, center_y = offset_x + tex_w / 2, offset_y + tex_h / 2

                area = next((int(row[f"AreaID_{i}"]) for i in range(4) if row[f"AreaID_{i}"] != "0"), 0)
                key = (offset_x, offset_y, tex_w, tex_h)
                entries[key] = (offset_x, offset_y, tex_w, tex_h,
                                round(center_x / width, 4), round(center_y / height, 4), area)

    return {ui_map: sorted(entries.values()) for ui_map, entries in zones.items() if entries}, skipped


def write_lua(path, zones, build, flavor):
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "local addonName, SN = ...",
        "",
        f"-- Generated by tools/gen-exploration.py from the {flavor} {build} tables. Do not edit by hand.",
        "-- [uiMapID] = { { offsetX, offsetY, textureWidth, textureHeight, centerX, centerY, areaID }, ... }",
        "SN.ExplorationData = {",
    ]
    for ui_map in sorted(zones):
        lines.append(f"    [{ui_map}] = {{")
        for entry in zones[ui_map]:
            lines.append("        { " + ", ".join(f"{value:g}" if isinstance(value, float) else str(value) for value in entry) + " },")
        lines.append("    },")
    lines.append("}")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--retail", default=DEFAULT_BUILDS["retail"])
    parser.add_argument("--forever", default=DEFAULT_BUILDS["forever"])
    args = parser.parse_args()

    for flavor, build in (("retail", args.retail), ("forever", args.forever)):
        zones, skipped = build_zones(build)
        write_lua(TARGETS[flavor], zones, build, flavor)
        count = sum(len(entries) for entries in zones.values())
        print(f"{flavor} {build}: {len(zones)} maps, {count} regions ({skipped} skipped: no art style) -> {TARGETS[flavor]}")


if __name__ == "__main__":
    main()
